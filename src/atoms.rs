/// The elements of a structure: a theory (a signature with axioms), and the
/// interpretation of the symbols of the signature.
pub trait Structure : Clone + Eq + Hash + Debug + 'static {
    /// The theory of the structure. The finite substructures of the structure
    /// are the finite structures of the signature that satisfy the axioms.
    fn theory() -> &'static Theory;

    /// Whether the relation number `r` of the signature holds for `args`.
    fn holds(r : usize, args : &[Self]) -> bool;

    /// The value of the function number `f` of the signature at `args`.
    fn apply(f : usize, args : &[Self]) -> Self;
}

/// A declaration, with no methods, that a structure is homogeneous: every
/// isomorphism between finite substructures generated by elements extends to
/// an automorphism. Nothing checks it: if the declaration is wrong, the orbits
/// computed for the structure are wrong. The substructures generated by finite
/// sets must be finite.
pub trait HomogeneousStructure : Structure {}

/// Atoms: the elements of a structure, with the orbits of its automorphism group.
pub trait Atoms : Structure {
    /// Whether some automorphism maps the tuple `first` to the tuple `second`.
    fn tuples_in_same_orbit(first : &[Self], second : &[Self]) -> bool;
}

/// Every homogeneous structure gives atoms, with the canonical orbit test.
impl<S : HomogeneousStructure> Atoms for S {
    fn tuples_in_same_orbit(first : &[Self], second : &[Self]) -> bool {
        homogeneous_tuples_in_same_orbit(first, second)
    }
}

/// The position of `x` in `v`.
fn position<S : PartialEq>(v : &[S], x : &S) -> Option<usize> {
    v.iter().position(|y| y == x)
}

/// All tuples of length `k` of numbers smaller than `n`.
fn index_tuples(n : usize, k : usize) -> Vec<Vec<usize>> {
    let mut tuples = vec![Vec::new()];
    for _ in 0..k {
        tuples = tuples.into_iter().flat_map(|t| (0..n).map(move |i| [t.clone(), vec![i]].concat())).collect();
    }
    tuples
}

/// The canonical orbit test for homogeneous structures: whether the map that
/// sends `first[i]` to `second[i]` is well defined, injective, and extends to an
/// isomorphism between the substructures generated by `first` and by `second`.
/// In a homogeneous structure, this holds if and only if some automorphism maps
/// `first` to `second`. It uses only `holds` and `apply`, so it is equivariant.
pub fn homogeneous_tuples_in_same_orbit<S : Structure>(first : &[S], second : &[S]) -> bool {
    if first.len() != second.len() {
        return false;
    }
    let signature = &S::theory().signature;
    // The map, as two lists: a[i] is mapped to b[i].
    let mut a : Vec<S> = Vec::new();
    let mut b : Vec<S> = Vec::new();
    // Adds the pair (x, y), and returns Some(true) if it is new, Some(false) if
    // it is already there, and None if the map would not be a bijection.
    let add = |a : &mut Vec<S>, b : &mut Vec<S>, x : S, y : S| -> Option<bool> {
        match (position(a, &x), position(b, &y)) {
            (Some(i), Some(j)) => (i == j).then_some(false),
            (None, None) => {
                a.push(x);
                b.push(y);
                Some(true)
            }
            _ => None,
        }
    };
    for (x, y) in first.iter().zip(second) {
        if add(&mut a, &mut b, x.clone(), y.clone()).is_none() {
            return false;
        }
    }
    // Close under the functions, until no new pair appears.
    loop {
        let mut new = false;
        for (f, (_, arity)) in signature.functions.iter().enumerate() {
            for args in index_tuples(a.len(), *arity) {
                let x = S::apply(f, &args.iter().map(|&i| a[i].clone()).collect::<Vec<_>>());
                let y = S::apply(f, &args.iter().map(|&i| b[i].clone()).collect::<Vec<_>>());
                match add(&mut a, &mut b, x, y) {
                    None => return false,
                    Some(added) => new |= added,
                }
            }
        }
        if !new {
            break;
        }
    }
    // Check the relations, including the order if the signature has one.
    signature.relations.iter().enumerate().all(|(r, (_, arity))| {
        index_tuples(a.len(), *arity).iter().all(|args| {
            S::holds(r, &args.iter().map(|&i| a[i].clone()).collect::<Vec<_>>())
                == S::holds(r, &args.iter().map(|&i| b[i].clone()).collect::<Vec<_>>())
        })
    })
}

/// The diagram of a tuple of length k: a formula in the variables 0, ..., k - 1
/// that holds at a tuple of length k exactly when the substructures generated
/// by the two tuples are isomorphic by the map between the tuples. It names every element of the
/// generated substructure by a term, and lists the equalities between the
/// variables, the relations between the elements, and the values of the
/// functions. It only depends on the orbit of the tuple. In a homogeneous
/// structure, it defines the orbit of the tuple.
///
/// If the signature has the order `<`, which must then be a linear order,
/// only the instances t < u where no element lies between t and u are listed:
/// the others follow by transitivity, and they also say that the elements are
/// distinct.
pub fn diagram<S : Structure>(tuple : &[S]) -> Formula {
    let signature = &S::theory().signature;
    let mut elements : Vec<S> = Vec::new();
    let mut terms : Vec<Term> = Vec::new();
    let mut conjuncts = Vec::new();
    for (i, a) in tuple.iter().enumerate() {
        match elements.iter().position(|b| b == a) {
            Some(p) => conjuncts.push(Formula::Eq(Term::Var(i), terms[p].clone())),
            None => {
                elements.push(a.clone());
                terms.push(Term::Var(i));
            }
        }
    }
    // Name the elements of the generated substructure.
    loop {
        let mut new = false;
        for (f, (_, arity)) in signature.functions.iter().enumerate() {
            for args in index_tuples(elements.len(), *arity) {
                let value = S::apply(f, &args.iter().map(|&i| elements[i].clone()).collect::<Vec<_>>());
                if !elements.contains(&value) {
                    elements.push(value);
                    terms.push(Term::App(f, args.iter().map(|&i| terms[i].clone()).collect()));
                    new = true;
                }
            }
        }
        if !new {
            break;
        }
    }
    let n = elements.len();
    let pick = |args : &[usize]| -> Vec<S> { args.iter().map(|&i| elements[i].clone()).collect() };
    let order = signature.relation("<");
    if order.is_none() {
        for q in 0..n {
            for p in 0..q {
                conjuncts.push(Formula::negate(Formula::Eq(terms[p].clone(), terms[q].clone())));
            }
        }
    }
    for (r, (_, arity)) in signature.relations.iter().enumerate() {
        for args in index_tuples(n, *arity) {
            let atom = Formula::Rel(r, args.iter().map(|&i| terms[i].clone()).collect());
            let holds = S::holds(r, &pick(&args));
            if Some(r) == order {
                let between = |c : usize| S::holds(r, &pick(&[args[0], c])) && S::holds(r, &pick(&[c, args[1]]));
                if holds && !(0..n).any(between) {
                    conjuncts.push(atom);
                }
            } else {
                conjuncts.push(if holds { atom } else { Formula::negate(atom) });
            }
        }
    }
    for (f, (_, arity)) in signature.functions.iter().enumerate() {
        for args in index_tuples(n, *arity) {
            let value = S::apply(f, &pick(&args));
            let p = elements.iter().position(|b| *b == value).unwrap();
            let term = Term::App(f, args.iter().map(|&i| terms[i].clone()).collect());
            if terms[p] != term {
                conjuncts.push(Formula::Eq(term, terms[p].clone()));
            }
        }
    }
    Formula::And(conjuncts)
}

/// The value of a term of the signature of `S` at an assignment of elements to
/// its variables.
pub fn evaluate_term<S : Structure>(t : &Term, assignment : &[S]) -> S {
    match t {
        Term::Var(i) => assignment[*i].clone(),
        Term::App(f, args) => S::apply(*f, &args.iter().map(|a| evaluate_term(a, assignment)).collect::<Vec<_>>()),
    }
}

/// Whether a formula of the signature of `S` holds at an assignment of elements
/// to its variables.
pub fn satisfies<S : Structure>(formula : &Formula, assignment : &[S]) -> bool {
    match formula {
        Formula::True => true,
        Formula::False => false,
        Formula::Eq(s, t) => evaluate_term(s, assignment) == evaluate_term(t, assignment),
        Formula::Rel(r, args) => S::holds(*r, &args.iter().map(|a| evaluate_term(a, assignment)).collect::<Vec<_>>()),
        Formula::Not(a) => !satisfies(a, assignment),
        Formula::And(v) => v.iter().all(|a| satisfies(a, assignment)),
        Formula::Or(v) => v.iter().any(|a| satisfies(a, assignment)),
    }
}

/// The theory of the type `T`, built by `build` the first time and kept for the
/// rest of the program. A generic type such as `Coloured<A>` cannot keep its
/// theory in a static of its own, because all instances of a generic function
/// share its statics; this registry keeps one theory for each type.
pub fn theory_of_type<T : 'static>(build : impl FnOnce() -> Theory) -> &'static Theory {
    static THEORIES : OnceLock<Mutex<HashMap<TypeId, &'static Theory>>> = OnceLock::new();
    let theories = THEORIES.get_or_init(|| Mutex::new(HashMap::new()));
    if let Some(t) = theories.lock().unwrap().get(&TypeId::of::<T>()) {
        return t;
    }
    // Build outside the lock, since `build` may need the theories of other types.
    let built : &'static Theory = Box::leak(Box::new(build()));
    let mut map = theories.lock().unwrap();
    map.entry(TypeId::of::<T>()).or_insert(built);
    map[&TypeId::of::<T>()]
}

/// Atoms of a structure with a linear order that every automorphism preserves,
/// such as the dense linear order (Q, <). This is what the Gröbner basis
/// algorithms need: the monomial order is built from the order of the atoms.
///
/// The order is Rust's `Ord`, and the signature must have the relation `<`,
/// interpreted by `holds` as this order, so that the orbit tests see it.
/// An automorphism that maps a finite set S onto a finite set T restricts to
/// the increasing bijection from S onto T, which is why finite sets of atoms
/// are stored as sorted sets.
/// An orbit of pairs of finite sets of atoms.
pub type SetPairOrbit<A> = Orbit<A, (BTreeSet<A>, BTreeSet<A>)>;

pub trait AtomsWithOrd : Atoms + Ord {

    /// Whether some automorphism maps the set `first` onto the set `second`.
    /// The default compares the two sets as tuples in increasing order, which is
    /// correct since automorphisms preserve the order.
    fn in_same_orbit(first : &BTreeSet<Self>, second : &BTreeSet<Self>) -> bool {
        first.len() == second.len()
            && Self::tuples_in_same_orbit(&first.iter().cloned().collect::<Vec<_>>(), &second.iter().cloned().collect::<Vec<_>>())
    }

    /// The orbits of pairs of finite sets in the product of the orbit of `first`
    /// and the orbit of `second`. The result only depends on these two orbits.
    fn orbits_in_product(first : &BTreeSet<Self>, second : &BTreeSet<Self>)
        -> Vec<SetPairOrbit<Self>>;
}

/// The answers of `cached_orbits_in_product`, for one type of atoms: the key
/// is the pair of the sizes and the diagrams of the two sets.
type ProductCache<A> = HashMap<((usize, Formula), (usize, Formula)), Vec<SetPairOrbit<A>>>;

thread_local! {
    /// The caches of `cached_orbits_in_product`, one for each type of atoms.
    static PRODUCT_CACHES : RefCell<HashMap<TypeId, Box<dyn Any>>> = RefCell::new(HashMap::new());
}

/// `orbits_in_product` with a cache, for homogeneous structures, where it is
/// worth it: `compute` answers the questions that are not in the cache yet.
///
/// The answer only depends on the orbits of `first` and `second`. In a
/// homogeneous structure, the diagram of a tuple of a given length identifies
/// its orbit: it only depends on the orbit, and it defines the orbit. So the
/// sizes and the diagrams of the two sets, listed in increasing order,
/// identify the question. The sizes are needed: the empty tuple and a single
/// atom, for example, both have the empty diagram. Each thread has its own
/// cache, which is kept until the end of the thread.
pub fn cached_orbits_in_product<A : AtomsWithOrd + HomogeneousStructure>(
    first : &BTreeSet<A>,
    second : &BTreeSet<A>,
    compute : impl FnOnce(&BTreeSet<A>, &BTreeSet<A>) -> Vec<SetPairOrbit<A>>,
) -> Vec<SetPairOrbit<A>> {
    let sorted = |set : &BTreeSet<A>| set.iter().cloned().collect::<Vec<A>>();
    let key = ((first.len(), diagram(&sorted(first))), (second.len(), diagram(&sorted(second))));
    let known = PRODUCT_CACHES.with(|caches| {
        caches
            .borrow()
            .get(&TypeId::of::<A>())
            .and_then(|cache| cache.downcast_ref::<ProductCache<A>>())
            .and_then(|cache| cache.get(&key).cloned())
    });
    if let Some(orbits) = known {
        return orbits;
    }
    // The cache is not borrowed during the computation, which may use the
    // caches of other types.
    let orbits = compute(first, second);
    PRODUCT_CACHES.with(|caches| {
        caches
            .borrow_mut()
            .entry(TypeId::of::<A>())
            .or_insert_with(|| Box::new(ProductCache::<A>::new()))
            .downcast_mut::<ProductCache<A>>()
            .expect("each type of atoms has a cache of its own type")
            .insert(key, orbits.clone());
    });
    orbits
}

/// The orbit of an element with atoms, given by a representative.
/// The representative is private, so that orbits can only be used through the
/// operations below. Applied to equivariant functions, these operations are
/// equivariant.
#[derive(Clone)]
pub struct Orbit<A : AtomsWithOrd, B : ElementsWithAtoms<A>> {
    rep : B,
    atoms : PhantomData<A>
}

impl<A : AtomsWithOrd, B : ElementsWithAtoms<A>> Orbit<A, B> {

    /// The orbit of `rep`.
    pub fn new(rep : B) -> Self {
        Orbit { rep, atoms : PhantomData }
    }

    /// The representative, for the implementations of the traits in this crate
    /// (such as `Coloured<A>`, which builds its orbits from those of `A`). It is
    /// not public, since it is not an equivariant function of the orbit.
    pub(crate) fn representative(&self) -> &B {
        &self.rep
    }

    /// The elements of the orbit whose support is contained in `support`.
    pub fn supported_by(&self, support : &BTreeSet<A>) -> Vec<B> {
        B::project_to_support(&self.rep, support)
    }

    /// The orbits of pairs in the product of `self` and `other`.
    ///
    /// For ordered atoms, the orbit of a pair (x, y) is determined by the orbit
    /// of the pair of supports (supp(x), supp(y)), so we take the images of the
    /// representatives under the partial automorphisms onto each representative
    /// pair of supports.
    pub fn product<C : ElementsWithAtoms<A>>(&self, other : &Orbit<A, C>) -> Vec<Orbit<A, (B, C)>> {
        let first = self.rep.support();
        let second = other.rep.support();
        A::orbits_in_product(&first, &second)
            .into_iter()
            .map(|pair| {
                let (s, t) = &pair.rep;
                let to_s = PartialAut::new(&first, s).expect("orbits_in_product returned a set in another orbit");
                let to_t = PartialAut::new(&second, t).expect("orbits_in_product returned a set in another orbit");
                Orbit::new((self.rep.apply_paut(&to_s), other.rep.apply_paut(&to_t)))
            })
            .collect()
    }

    /// The image of the orbit under a function `f`, which must be equivariant.
    pub fn map<C : ElementsWithAtoms<A>>(&self, f : impl Fn(&B) -> C) -> Orbit<A, C> {
        Orbit::new(f(&self.rep))
    }

    /// The value of a function `f` on the orbit. The function must be invariant,
    /// that is, f(π(b)) = f(b) for every automorphism π, so it is constant on the
    /// orbit. Examples are the degree of a polynomial and the size of a support.
    pub fn evaluate<T>(&self, f : impl Fn(&B) -> T) -> T {
        f(&self.rep)
    }

    /// The orbit itself if the predicate `p` holds on it, and `None` otherwise.
    /// The predicate must be equivariant, so it is constant on the orbit.
    pub fn filter(&self, p : impl Fn(&B) -> bool) -> Option<Orbit<A, B>> {
        if p(&self.rep) {
            Some(self.clone())
        } else {
            None
        }
    }
}

impl<A : AtomsWithOrd, B : ElementsWithAtoms<A>> PartialEq for Orbit<A, B> {
    fn eq(&self, other : &Self) -> bool {
        B::tuples_in_same_orbit(std::slice::from_ref(&self.rep), std::slice::from_ref(&other.rep))
    }
}

impl<A : AtomsWithOrd, B : ElementsWithAtoms<A>> Eq for Orbit<A, B> {}

/// Shows the orbit through its representative, for debugging only.
impl<A : AtomsWithOrd, B : ElementsWithAtoms<A> + Debug> Debug for Orbit<A, B> {
    fn fmt(&self, f : &mut Formatter<'_>) -> Result {
        write!(f, "orbit of {:?}", self.rep)
    }
}

/// Displays the orbit through its representative, for output only.
impl<A : AtomsWithOrd, B : ElementsWithAtoms<A> + Display> Display for Orbit<A, B> {
    fn fmt(&self, f : &mut Formatter<'_>) -> Result {
        write!(f, "orbit of {}", self.rep)
    }
}

