use std::collections::BTreeSet;
use std::hash::Hash;
use std::ops::{AddAssign, Div, Neg, Sub};
use num_traits::{ConstOne, Zero};

use crate::mon::*;

/// An ideal of a polynomial ring, stored by its reduced Gröbner basis.
/// Since the reduced Gröbner basis of an ideal is unique, two ideals are equal
/// if and only if their stored bases are equal.
#[derive(Clone)]
pub struct Ideal<F, X : Ord + Hash + Clone> {
    basis : Vec<Polynomial<F, X>>
}

impl <F : AddAssign + Clone + ConstOne + Default + Zero + Eq + Div<Output = F> + Neg<Output = F> + Sub + Ord,
      X : Ord + Hash + Clone> Ideal<F,X> {

    /// The ideal generated by `generators`.
    pub fn new(generators : Vec<Polynomial<F,X>>) -> Ideal<F,X> {
        Ideal { basis : buchberger(generators) }
    }

    /// The reduced Gröbner basis of the ideal.
    pub fn groebner_basis(&self) -> &[Polynomial<F,X>] {
        &self.basis
    }

    /// Whether `f` belongs to the ideal: its normal form with respect to a
    /// Gröbner basis is zero.
    pub fn contains(&self, f : &Polynomial<F,X>) -> bool {
        f.clone().normal_form(&self.basis).is_zero()
    }

    /// Whether the ideal is contained in `other`.
    pub fn is_subset(&self, other : &Ideal<F,X>) -> bool {
        self.basis.iter().all(|g| other.contains(g))
    }

    /// The sum I + J, generated by the union of generators.
    pub fn sum(&self, other : &Ideal<F,X>) -> Ideal<F,X> {
        Ideal::new(self.basis.iter().chain(other.basis.iter()).cloned().collect())
    }

    /// The product I J, generated by the products g h of generators g of I and h of J.
    pub fn product(&self, other : &Ideal<F,X>) -> Ideal<F,X> {
        let mut generators = Vec::new();
        for g in self.basis.iter() {
            for h in other.basis.iter() {
                generators.push(g.clone() * h.clone());
            }
        }
        Ideal::new(generators)
    }
}

impl<F : PartialEq, X : Ord + Hash + Clone> PartialEq for Ideal<F,X> {
    fn eq(&self, other : &Self) -> bool {
        self.basis == other.basis
    }
}

impl<F : PartialEq, X : Ord + Hash + Clone> Eq for Ideal<F,X> {}

/// Buchberger's algorithm with Buchberger's two criteria, in the form of
/// Cox, Little and O'Shea, "Ideals, Varieties, and Algorithms", Section 2.10.
/// Returns a Gröbner basis of the ideal generated by `generators`.
pub fn buchberger<
F : AddAssign + Clone + ConstOne + Default + Zero + Eq + Div<Output = F> + Neg<Output = F> + Sub + Ord,
X : Ord + Hash + Clone>
(generators : Vec<Polynomial<F,X>>) -> Vec<Polynomial<F,X>> {
    // Zero polynomials do not change the ideal and have no leading term.
    let mut basis : Vec<Polynomial<F,X>> = Vec::new();
    for g in generators {
        if !g.is_zero() && !basis.contains(&g) {
            basis.push(g);
        }
    }
    // The pairs (i, j), i < j, whose S-polynomials have not been treated yet.
    let mut pairs : BTreeSet<(usize, usize)> = BTreeSet::new();
    for j in 0..basis.len() {
        for i in 0..j {
            pairs.insert((i, j));
        }
    }
    while let Some((i, j)) = select_pair(&pairs, &basis) {
        pairs.remove(&(i, j));
        let lm_i = basis[i].leading_mon();
        let lm_j = basis[j].leading_mon();
        // First criterion: if the leading monomials are coprime,
        // the S-polynomial reduces to zero.
        if lm_i.lcm(&lm_j) == lm_i.clone() * lm_j.clone() {
            continue;
        }
        // Second (chain) criterion.
        if chain_criterion(i, j, &pairs, &basis) {
            continue;
        }
        let r = basis[i].clone().syzygy(&basis[j]).normal_form(&basis);
        if !r.is_zero() {
            let k = basis.len();
            basis.push(r);
            for i in 0..k {
                pairs.insert((i, k));
            }
        }
    }
    reduce_groebner_basis(basis)
}

/// Turns a Gröbner basis into the reduced Gröbner basis of the same ideal:
/// removes the elements whose leading monomial is divisible by the leading
/// monomial of another element, replaces each remaining element by its normal
/// form with respect to the others, and makes it monic.
/// The result is sorted, so equal ideals give equal results.
pub fn reduce_groebner_basis<
F : AddAssign + Clone + ConstOne + Default + Zero + Eq + Div<Output = F> + Neg<Output = F> + Ord,
X : Ord + Hash + Clone>
(basis : Vec<Polynomial<F,X>>) -> Vec<Polynomial<F,X>> {
    let mut sorted : Vec<Polynomial<F,X>> = basis.into_iter().filter(|g| !g.is_zero()).collect();
    // A divisor of a monomial is smaller in any monomial order, so after sorting
    // every possible divisor of a leading monomial comes first.
    sorted.sort_by_key(|g| g.leading_mon());
    let mut minimal : Vec<Polynomial<F,X>> = Vec::new();
    for g in sorted {
        if !minimal.iter().any(|h| g.leading_mon().is_divisible_by(&h.leading_mon())) {
            minimal.push(g);
        }
    }
    let reduced : BTreeSet<Polynomial<F,X>> = (0..minimal.len())
        .map(|i| {
            let others : Vec<Polynomial<F,X>> = minimal.iter().enumerate()
                .filter(|&(j, _)| j != i)
                .map(|(_, h)| h.clone())
                .collect();
            minimal[i].clone().normal_form(&others).monic()
        })
        .collect();
    reduced.into_iter().collect()
}

/// Normal selection strategy: a pair whose leading monomials have the smallest lcm.
fn select_pair<F, X>(pairs : &BTreeSet<(usize, usize)>, basis : &[Polynomial<F,X>]) -> Option<(usize, usize)>
where
    F : AddAssign + Default + Eq + Zero + ConstOne + Clone,
    X : Ord + Hash + Clone,
{
    pairs
        .iter()
        .map(|&(i, j)| (basis[i].leading_mon().lcm(&basis[j].leading_mon()), (i, j)))
        .min()
        .map(|(_, pair)| pair)
}

/// Chain criterion: the pair (i, j) can be skipped if some k other than i and j
/// has LM(g_k) dividing lcm(LM(g_i), LM(g_j)) and the pairs {i, k} and {j, k}
/// have already been treated.
fn chain_criterion<F, X>(i : usize, j : usize, pairs : &BTreeSet<(usize, usize)>, basis : &[Polynomial<F,X>]) -> bool
where
    F : AddAssign + Default + Eq + Zero + ConstOne + Clone,
    X : Ord + Hash + Clone,
{
    let lcm = basis[i].leading_mon().lcm(&basis[j].leading_mon());
    let pending = |a : usize, b : usize| pairs.contains(&(a.min(b), a.max(b)));
    (0..basis.len()).any(|k| {
        k != i && k != j
            && !pending(i, k)
            && !pending(j, k)
            && lcm.is_divisible_by(&basis[k].leading_mon())
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::bits::F2;
    use num_traits::One;

    type P2 = Polynomial<F2, String>;

    fn v2(name : &str) -> P2 { Polynomial::var(name.to_string()) }

    #[test]
    fn buchberger_ignores_zero_polynomials() {
        let x = v2("x");
        assert_eq!(buchberger(vec![P2::zero(), x.clone()]), vec![x]);
        assert!(buchberger(vec![P2::zero()]).is_empty());
    }

    /// Checks Buchberger's criterion: every S-polynomial reduces to zero.
    fn is_groebner_basis(basis : &[P2]) -> bool {
        basis.iter().enumerate().all(|(i, f)| {
            basis[i + 1..].iter().all(|g| f.clone().syzygy(g).remainder(basis).is_zero())
        })
    }

    #[test]
    fn buchberger_example_from_main() {
        let (x, y, z) = (v2("x"), v2("y"), v2("z"));
        let basis = buchberger(vec![x.clone() * y.clone(), x.clone() + y.clone() * z.clone()]);
        assert!(is_groebner_basis(&basis));
        assert!(basis.contains(&(x.clone() * x.clone())));
        // The reduced Gröbner basis is {x^2, xy, x + yz}.
        let mut expected = vec![x.clone() * x.clone(), x.clone() * y.clone(), x.clone() + y.clone() * z.clone()];
        expected.sort();
        assert_eq!(basis, expected);
    }

    #[test]
    fn ideal_membership_and_equality() {
        let (x, y, z) = (v2("x"), v2("y"), v2("z"));
        let i = Ideal::new(vec![x.clone() * y.clone(), x.clone() + y.clone() * z.clone()]);
        assert!(i.contains(&(x.clone() * x.clone())));
        assert!(i.contains(&(x.clone() * y.clone() * z.clone() + x.clone() * x.clone())));
        assert!(!i.contains(&y));
        assert!(!i.contains(&P2::one()));
        // The same ideal from different generators.
        let j = Ideal::new(vec![x.clone() + y.clone() * z.clone(), x.clone() * x.clone(), x.clone() * y.clone()]);
        assert!(i == j);
        assert!(i != Ideal::new(vec![x.clone()]));
        // The zero ideal only contains 0.
        let zero : Ideal<F2, String> = Ideal::new(vec![]);
        assert!(zero.contains(&P2::zero()));
        assert!(!zero.contains(&x));
    }

    #[test]
    fn ideal_sum_and_product() {
        let (x, y) = (v2("x"), v2("y"));
        let ix = Ideal::new(vec![x.clone()]);
        let iy = Ideal::new(vec![y.clone()]);
        let sum = ix.sum(&iy);
        assert!(sum == Ideal::new(vec![x.clone(), y.clone()]));
        assert!(sum.contains(&(x.clone() + y.clone())));
        let product = ix.product(&iy);
        assert!(product == Ideal::new(vec![x.clone() * y.clone()]));
        assert!(!product.contains(&x));
        assert!(product.is_subset(&ix) && product.is_subset(&iy));
        assert!(ix.is_subset(&sum) && !sum.is_subset(&ix));
    }

    #[test]
    fn reduced_basis_over_q() {
        use num_rational::Rational64 as Q;
        let v = |n : &str| -> Polynomial<Q, String> { Polynomial::var(n.to_string()) };
        let c = |k : i64| -> Polynomial<Q, String> { Polynomial::constant(Q::from_integer(k)) };
        let (x, y) = (v("x"), v("y"));
        // <2x - y, x^2 - 1> with y > x: y = 2x, so the reduced basis is {y - 2x, x^2 - 1}.
        let basis = buchberger(vec![c(2) * x.clone() - y.clone(), x.clone() * x.clone() - c(1)]);
        let mut expected = vec![y.clone() - c(2) * x.clone(), x.clone() * x.clone() - c(1)];
        expected.sort();
        assert_eq!(basis, expected);
        // The same ideal from other generators gives the same reduced basis.
        let other = buchberger(vec![y.clone() * y.clone() - c(4), y.clone() - c(2) * x.clone()]);
        assert_eq!(other, expected);
    }
}
