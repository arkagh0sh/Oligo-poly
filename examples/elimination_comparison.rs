//! Compares three ways to compute, for an ideal I of K[x1, ..., xn], a basis B
//! such that for every set V of variables, the elements of B in K[X_V] form a
//! Gröbner basis of the elimination ideal I ∩ K[X_V]. Equivalently, every
//! non-zero f in I has an element h of B with supp(h) ⊆ supp(f) and LM(h)
//! dividing LM(f): B is an equivariant Gröbner basis for the trivial group.
//!
//! 1. Ordinary Buchberger: the reduced Gröbner basis of I (`ideal::buchberger`).
//!    By the Elimination Theorem, it has the property for V = {x1, ..., xk}, but
//!    not always for the other sets V.
//! 2. Elimination for every V: the union, over all 2^n sets V, of the reduced
//!    Gröbner bases of I ∩ K[X_V], each computed with an elimination order
//!    (`ideal::elimination_ideal`). This has the property by construction; it is
//!    the method of the footnote in Section 2 of Ghosh and Lopez.
//! 3. Colouring trick: `equivariant_groebner_basis` with the variables of
//!    `trivial.rs`, that is, forget(weakgb(freecol(H))) of Section 5 of Ghosh and
//!    Lopez. It runs one Buchberger algorithm with the support condition, on 2n
//!    coloured variables and 2^|supp h| colourings of each generator h.
//! 4. One-colour trick: `one_colour_groebner_basis`, the variant in which every
//!    coloured polynomial has at most one high variable, only pairs with
//!    consistent colours give S-polynomials, and new polynomials without a high
//!    variable are added again with each one of their variables high. It has
//!    the property (see `README.tex`); the column "failing V" checks it.
//!
//! For each method, the program prints the time, the number of polynomials of
//! the basis, the number of them that remain after removing every h for which
//! another kept h' has supp(h') ⊆ supp(h) and LM(h') dividing LM(h)
//! (`minimal_basis`), and the number of sets V for which the property fails.
//! The elimination ideals of method 2 serve as the reference for this check.
//!
//! Usage:
//!
//! ```sh
//! cargo run --release --features equivariant --example elimination_comparison -- \
//!     [--csv FILE] [--verbose] [--limit N] [--ideal "POLYNOMIALS"]
//!     [--random COUNT] [--vars N] [--seed SEED] [NAME ...]
//! ```
//!
//! - NAME: run only the built-in ideals whose name contains NAME. Without NAME
//!   and without `--ideal`, all built-in ideals run.
//! - `--ideal "POLYNOMIALS"`: run on the ideal generated by the given
//!   polynomials, separated by `;`. A polynomial is a sum of terms separated by
//!   `+`, and a term is a product of factors separated by `*`. A factor is a
//!   rational coefficient (such as `-3` or `2/5`) or a variable x1, x2, ... with
//!   an optional exponent (such as `x2^3`). Example: `--ideal "x2 + -1*x1; x1^2"`.
//!   The option can be repeated.
//! - `--csv FILE`: also write the results to FILE, in CSV format.
//! - `--verbose`: print the minimal bases and the sets V where the ordinary
//!   basis fails.
//! - `--limit N`: the largest number of coloured polynomials in the colouring
//!   tricks (default 2000).
//! - `--skip-colouring`: do not run method 3, which is the slowest.
//! - `--random COUNT`: also run on COUNT random ideals in `--vars` variables
//!   (default 4), each generated by 2 or 3 polynomials with 2 or 3 terms of
//!   degree 1 or 2. `--seed` changes the random ideals.
//!
//! At the end, the program prints for each method the total time and the
//! number of ideals for which the property fails for some set V.
//!
//! To add a built-in ideal, add a line to `main`.

use atomic_hilbert::atoms::Orbit;
use atomic_hilbert::equivariant::{equivariant_groebner_basis, minimal_basis, one_colour_groebner_basis, OrbitList};
use atomic_hilbert::ideal::{buchberger, elimination_ideal};
use atomic_hilbert::mon::Polynomial;
use atomic_hilbert::trivial::Var;
use num_rational::BigRational;
use num_traits::{One, Pow, Zero};
use std::collections::BTreeSet;
use std::fs::File;
use std::io::Write;
use std::time::{Duration, Instant};

type Q = BigRational;
type P = Polynomial<Q, Var>;

/// The command-line options.
struct Options {
    csv : Option<File>,
    verbose : bool,
    limit : usize,
    ideals : Vec<String>,
    random : usize,
    skip_colouring : bool,
    vars : u32,
    seed : u64,
    names : Vec<String>,
}

impl Options {
    fn parse() -> Options {
        let mut options = Options { csv : None, verbose : false, limit : 2000, ideals : Vec::new(), random : 0, skip_colouring : false, vars : 4, seed : 1, names : Vec::new() };
        let mut args = std::env::args().skip(1);
        while let Some(arg) = args.next() {
            match arg.as_str() {
                "--csv" => {
                    let path = args.next().expect("--csv needs a file name");
                    let mut file = File::create(&path).expect("cannot create the CSV file");
                    writeln!(file, "ideal,variables,method,ms,size,minimal,failing_sets").unwrap();
                    options.csv = Some(file);
                }
                "--verbose" => options.verbose = true,
                "--skip-colouring" => options.skip_colouring = true,
                "--limit" => options.limit = args.next().and_then(|v| v.parse().ok()).expect("--limit needs a number"),
                "--ideal" => options.ideals.push(args.next().expect("--ideal needs polynomials")),
                "--random" => options.random = args.next().and_then(|v| v.parse().ok()).expect("--random needs a number"),
                "--vars" => options.vars = args.next().and_then(|v| v.parse().ok()).expect("--vars needs a number"),
                "--seed" => options.seed = args.next().and_then(|v| v.parse().ok()).expect("--seed needs a number"),
                name => options.names.push(name.to_string()),
            }
        }
        options
    }

    /// Whether the built-in ideal `name` is selected.
    fn selected(&self, name : &str) -> bool {
        (self.names.is_empty() && self.ideals.is_empty() && self.random == 0) || self.names.iter().any(|n| name.contains(n.as_str()))
    }
}

/// Parses polynomials in the syntax described at the top of the file.
fn parse(src : &str) -> Vec<P> {
    src.split(';')
        .map(str::trim)
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut f = P::zero();
            for term in p.split('+').map(str::trim).filter(|t| !t.is_empty()) {
                let mut t = P::constant(Q::one());
                for factor in term.split('*').map(str::trim) {
                    if let Some(rest) = factor.strip_prefix('x') {
                        let mut it = rest.split('^');
                        let i : u32 = it.next().unwrap().trim().parse().expect("bad variable index");
                        let e : u32 = it.next().map(|e| e.trim().parse().expect("bad exponent")).unwrap_or(1);
                        t = t * x(i).pow(e);
                    } else {
                        t = t * P::constant(factor.parse::<Q>().expect("bad coefficient"));
                    }
                }
                f = f + t;
            }
            f
        })
        .collect()
}

fn x(i : u32) -> P {
    Polynomial::var(Var(i))
}

fn c(k : i64) -> P {
    Polynomial::constant(Q::from_integer(k.into()))
}

fn milliseconds(d : Duration) -> f64 {
    d.as_secs_f64() * 1000.0
}

/// The sets of variables among `vars`, as bit masks.
fn subsets(vars : &[Var]) -> Vec<BTreeSet<Var>> {
    (0..1usize << vars.len())
        .map(|mask| vars.iter().enumerate().filter(|(i, _)| mask >> i & 1 == 1).map(|(_, v)| *v).collect())
        .collect()
}

/// Whether the elements of `basis` in K[X_V] form a Gröbner basis of the ideal
/// with reduced Gröbner basis `elimination` (the elimination ideal I ∩ K[X_V]),
/// given that they belong to it: every leading monomial of `elimination` must be
/// divisible by the leading monomial of one of them.
fn has_property(basis : &[P], v : &BTreeSet<Var>, elimination : &[P]) -> bool {
    let inside : Vec<&P> = basis.iter().filter(|h| !h.is_zero() && h.domain().is_subset(v)).collect();
    elimination.iter().all(|e| inside.iter().any(|h| e.leading_mon().is_divisible_by(&h.leading_mon())))
}

/// The result of one method.
struct Outcome {
    name : &'static str,
    time : Duration,
    basis : Vec<P>,
}

/// Totals over all ideals, for each method: the time and the number of ideals for
/// which the property fails for some set V.
#[derive(Default)]
struct Summary {
    rows : Vec<(&'static str, Duration, usize, usize)>,
}

impl Summary {
    fn record(&mut self, name : &'static str, time : Duration, fails : bool) {
        match self.rows.iter_mut().find(|r| r.0 == name) {
            Some(r) => {
                r.1 += time;
                r.2 += usize::from(fails);
                r.3 += 1;
            }
            None => self.rows.push((name, time, usize::from(fails), 1)),
        }
    }
}

fn run(options : &mut Options, summary : &mut Summary, name : &str, generators : Vec<P>) {
    let vars : Vec<Var> = generators.iter().flat_map(|g| g.domain()).collect::<BTreeSet<Var>>().into_iter().collect();
    let sets = subsets(&vars);
    let shown : Vec<String> = generators.iter().map(|g| g.to_string()).collect();
    println!("== {name}: {} variables, {} sets V", vars.len(), sets.len());
    for g in &shown {
        println!("  generator: {g}");
    }

    // Method 2 first: its elimination ideals are the reference.
    let start = Instant::now();
    let eliminations : Vec<Vec<P>> = sets.iter().map(|v| elimination_ideal(&generators, v)).collect();
    let elimination_time = start.elapsed();
    let mut union : Vec<P> = Vec::new();
    for e in eliminations.iter().flatten() {
        if !union.contains(e) {
            union.push(e.clone());
        }
    }

    let start = Instant::now();
    let ordinary = buchberger(generators.clone());
    let ordinary_time = start.elapsed();

    let start = Instant::now();
    let orbits : OrbitList<Q, Var> = generators.iter().cloned().map(Orbit::new).collect();
    let colouring = if options.skip_colouring { None } else { Some(equivariant_groebner_basis(orbits, options.limit)) };
    let colouring_time = start.elapsed();

    let mut outcomes = vec![
        Outcome { name : "ordinary Buchberger", time : ordinary_time, basis : ordinary },
        Outcome { name : "elimination for every V", time : elimination_time, basis : union },
    ];
    let start = Instant::now();
    let one_colour = one_colour_groebner_basis(generators.iter().cloned().map(Orbit::new).collect(), options.limit);
    let one_colour_time = start.elapsed();
    for (name, result, time) in [("colouring trick", colouring, colouring_time), ("one-colour trick", Some(one_colour), one_colour_time)] {
        let Some(result) = result else { continue };
        match result {
            Ok(basis) => outcomes.push(Outcome { name, time, basis : basis.iter().map(|o| o.evaluate(|p| p.clone())).collect() }),
            Err(partial) => println!(
                "  {name}: stopped after {} polynomials ({:.1} ms); raise --limit",
                partial.len(),
                milliseconds(time)
            ),
        }
    }

    println!("  {:<26} {:>12} {:>6} {:>8} {:>10}", "method", "ms", "size", "minimal", "failing V");
    for outcome in &outcomes {
        let failing : Vec<&BTreeSet<Var>> = sets
            .iter()
            .zip(eliminations.iter())
            .filter(|(v, e)| !has_property(&outcome.basis, v, e))
            .map(|(v, _)| v)
            .collect();
        let minimal : Vec<P> = minimal_basis(outcome.basis.iter().cloned().map(Orbit::new).collect())
            .iter()
            .map(|o| o.evaluate(|p| p.clone()))
            .collect();
        summary.record(outcome.name, outcome.time, !failing.is_empty());
        println!(
            "  {:<26} {:>12.1} {:>6} {:>8} {:>10}",
            outcome.name,
            milliseconds(outcome.time),
            outcome.basis.len(),
            minimal.len(),
            failing.len()
        );
        if let Some(file) = options.csv.as_mut() {
            writeln!(
                file,
                "{name},{},{},{:.3},{},{},{}",
                vars.len(),
                outcome.name,
                milliseconds(outcome.time),
                outcome.basis.len(),
                minimal.len(),
                failing.len()
            )
            .unwrap();
        }
        if (outcome.name == "elimination for every V" || outcome.name == "colouring trick") && !failing.is_empty() {
            println!("    error: this method must have the property for every set V");
        }
        if options.verbose {
            for v in &failing {
                println!("      fails for V = {v:?}");
            }
            for g in &minimal {
                println!("      {g}");
            }
        }
    }
    println!();
}

/// A small deterministic pseudo-random generator (xorshift).
struct Rng(u64);

impl Rng {
    fn below(&mut self, n : u64) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0 % n
    }
}

/// `count` random polynomials in x1, ..., xn, each with `terms` terms of degree 1
/// or 2 and coefficients in {-2, ..., 2}. The polynomials are drawn again until
/// none of them is zero and every variable occurs.
fn random_ideal(seed : u64, n : u32, count : usize, terms : usize) -> Vec<P> {
    let mut rng = Rng(seed);
    loop {
        let generators : Vec<P> = (0..count)
            .map(|_| {
                (0..terms).fold(P::zero(), |f, _| {
                    let mut t = c(rng.below(5) as i64 - 2);
                    for _ in 0..1 + rng.below(2) {
                        t = t * x(1 + rng.below(n as u64) as u32);
                    }
                    f + t
                })
            })
            .collect();
        let vars : BTreeSet<Var> = generators.iter().flat_map(|g| g.domain()).collect();
        if generators.iter().all(|g| !g.is_zero()) && vars.len() == n as usize {
            return generators;
        }
    }
}

fn main() {
    let mut options = Options::parse();
    let builtin : Vec<(&str, Vec<P>)> = vec![
        ("two-variables", vec![x(2) - x(1), x(1).pow(2u8)]),
        ("twisted-cubic", vec![x(2) - x(1).pow(2u8), x(3) - x(1).pow(3u8)]),
        ("circle-and-plane", vec![x(1).pow(2u8) + x(2).pow(2u8) - c(1), x(3) - x(1) - x(2)]),
        ("binomials", vec![x(1) * x(2) - x(3), x(2) * x(3) - x(1), x(1) * x(3) - x(2)]),
        ("cyclic-3", vec![x(1) + x(2) + x(3), x(1) * x(2) + x(2) * x(3) + x(1) * x(3), x(1) * x(2) * x(3) - c(1)]),
        ("linear-4", vec![x(1) + x(2) + x(3) + x(4), x(1) - x(2) + c(2) * x(3) - x(4)]),
        ("random-3", random_ideal(0x9e3779b97f4a7c15, 3, 3, 3)),
        ("random-4", random_ideal(0x2545f4914f6cdd1d, 4, 3, 3)),
    ];
    let mut summary = Summary::default();
    for (name, generators) in builtin {
        if options.selected(name) {
            run(&mut options, &mut summary, name, generators);
        }
    }
    let ideals = options.ideals.clone();
    for (i, src) in ideals.iter().enumerate() {
        run(&mut options, &mut summary, &format!("ideal-{}", i + 1), parse(src));
    }
    let mut rng = Rng(0x9e3779b97f4a7c15 ^ options.seed.wrapping_mul(0x2545f4914f6cdd1d));
    for i in 0..options.random {
        let (count, terms) = (2 + rng.below(2) as usize, 2 + rng.below(2) as usize);
        let vars = options.vars;
        let generators = random_ideal(rng.below(u64::MAX) | 1, vars, count, terms);
        run(&mut options, &mut summary, &format!("random-{vars}-{}", i + 1), generators);
    }
    println!("== summary");
    println!("  {:<26} {:>12} {:>8} {:>16}", "method", "total ms", "ideals", "ideals failing");
    for (name, time, failing, count) in &summary.rows {
        println!("  {:<26} {:>12.1} {:>8} {:>16}", name, milliseconds(*time), count, failing);
    }
}
