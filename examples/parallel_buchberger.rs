//! Compares the sequential Buchberger algorithm (`ideal::buchberger`) with the
//! two parallel versions of `parallel.rs`:
//!
//! - batch: in each round, all pending S-polynomials are reduced in parallel and
//!   all non-zero remainders are added;
//! - first: in each round, the pending S-polynomials are reduced in parallel in
//!   the order of the normal strategy, and only the first one that does not
//!   reduce to zero is added; the pairs that reduced to zero are marked as done.
//!
//! Each run (ideal, method, number of threads) happens in a child process with a
//! time limit, and the runs happen one after another, so that every run can use
//! all the cores. The time is measured in the child. Every result is compared
//! with the reduced Gröbner basis of the sequential algorithm.
//!
//! Usage:
//!
//! ```sh
//! cargo run --release --example parallel_buchberger -- \
//!     [--threads 1,2,4] [--timeout SECONDS] [--csv FILE] [NAME ...] \
//!     [--random COUNT --vars N --gens G --terms T --degree D --seed S]
//! ```
//!
//! - NAME: run only the built-in ideals whose name contains NAME (cyclic-4,
//!   cyclic-5, katsura-3, katsura-4, katsura-5, quadrics-4). Without NAME and
//!   without `--random`, all built-in ideals run.
//! - `--threads`: the numbers of threads for the parallel versions (default
//!   1,2,4).
//! - `--timeout`: the time limit of one run, in seconds (default 120).
//! - `--random COUNT`: also run on COUNT random ideals of K[x1, ..., xn]
//!   (default n = 4), each generated by G polynomials (default 4) with T terms
//!   (default 4) of degree 1 to D (default 2), with coefficients in
//!   {-2, -1, 1, 2}.
//! - `--csv FILE`: also write one line per run to FILE.
//!
//! The monomial order is the lexicographic order of `mon.rs`, with x1 < x2 < ...
//! and the coefficients are rational numbers.

use atomic_hilbert::ideal::buchberger;
use atomic_hilbert::mon::Polynomial;
use atomic_hilbert::parallel::{buchberger_batch, buchberger_first, Stats};
use num_rational::BigRational;
use num_traits::{One, Pow, Zero};
use std::fs::File;
use std::io::{Read, Write};
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

type Q = BigRational;
type P = Polynomial<Q, u32>;

fn x(i : u32) -> P {
    Polynomial::var(i)
}

fn c(k : i64) -> P {
    Polynomial::constant(Q::from_integer(k.into()))
}

/// Writes a polynomial in the syntax read by `parse`; the variable i is x<i>.
fn to_syntax(p : &P) -> String {
    let terms : Vec<String> = p
        .monomials()
        .map(|m| {
            let mut t = p.coeff_of(m).to_string();
            for factor in m.to_string().trim_matches(|ch| ch == '(' || ch == ')').split_whitespace() {
                if factor != "1" {
                    t += "*x";
                    t += factor;
                }
            }
            t
        })
        .collect();
    if terms.is_empty() { "0".to_string() } else { terms.join(" + ") }
}

/// Reads a polynomial written by `to_syntax`.
fn parse(src : &str) -> P {
    let mut f = P::zero();
    for term in src.split('+').map(str::trim).filter(|t| !t.is_empty()) {
        let mut t = P::constant(Q::one());
        for factor in term.split('*').map(str::trim) {
            if let Some(rest) = factor.strip_prefix('x') {
                let mut it = rest.split('^');
                let i : u32 = it.next().unwrap().parse().expect("bad variable index");
                let e : u32 = it.next().map(|e| e.parse().expect("bad exponent")).unwrap_or(1);
                t = t * x(i).pow(e);
            } else {
                t = t * P::constant(factor.parse::<Q>().expect("bad coefficient"));
            }
        }
        f = f + t;
    }
    f
}

/// The cyclic n-roots system: the elementary symmetric-like sums of
/// x_i x_{i+1} ... x_{i+k-1} (indices mod n) for k < n, and x_1 ... x_n - 1.
fn cyclic(n : u32) -> Vec<P> {
    let mut generators = Vec::new();
    for k in 1..n {
        let mut f = P::zero();
        for i in 0..n {
            f = f + (0..k).fold(c(1), |t, l| t * x(1 + (i + l) % n));
        }
        generators.push(f);
    }
    generators.push((1..=n).fold(c(1), |t, i| t * x(i)) - c(1));
    generators
}

/// The Katsura system with n + 1 variables u_0, ..., u_n, where u_l is x_{l+1}
/// and u_{-l} = u_l: sum_{l=-n}^{n} u_l = 1, and
/// sum_{l=-n}^{n} u_l u_{m-l} = u_m for m = 0, ..., n - 1 (u_l = 0 if |l| > n).
fn katsura(n : i64) -> Vec<P> {
    let u = |l : i64| -> P { if l.abs() > n { P::zero() } else { x(l.unsigned_abs() as u32 + 1) } };
    let mut generators = vec![(-n..=n).fold(P::zero(), |f, l| f + u(l)) - c(1)];
    for m in 0..n {
        generators.push((-n..=n).fold(P::zero(), |f, l| f + u(l) * u(m - l)) - u(m));
    }
    generators
}

/// A small deterministic pseudo-random generator (xorshift).
struct Rng(u64);

impl Rng {
    fn below(&mut self, n : u64) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0 % n
    }
}

fn random_ideal(rng : &mut Rng, n : u32, gens : usize, terms : usize, degree : u64) -> Vec<P> {
    (0..gens)
        .map(|_| {
            (0..terms).fold(P::zero(), |f, _| {
                let mut t = c([-2, -1, 1, 2][rng.below(4) as usize]);
                for _ in 0..1 + rng.below(degree) {
                    t = t * x(1 + rng.below(n as u64) as u32);
                }
                f + t
            })
        })
        .filter(|g| !g.is_zero())
        .collect()
}

/// The child process: reads the generators, runs the method, and prints the
/// time, the statistics and the basis.
fn child(method : &str, threads : usize) {
    let mut input = String::new();
    std::io::stdin().read_to_string(&mut input).unwrap();
    let generators : Vec<P> = input.lines().filter(|l| !l.trim().is_empty()).map(parse).collect();
    let start = Instant::now();
    let (basis, stats) = match method {
        "sequential" => (buchberger(generators), Stats::default()),
        "batch" => buchberger_batch(generators, threads),
        "first" => buchberger_first(generators, threads),
        _ => panic!("unknown method {method}"),
    };
    let time = start.elapsed();
    println!("time {}", time.as_secs_f64() * 1000.0);
    println!("stats {} {} {} {}", stats.rounds, stats.reductions, stats.zero, stats.discarded);
    for p in basis {
        println!("poly {}", to_syntax(&p));
    }
}

/// The result of one run.
struct Run {
    ms : f64,
    stats : Stats,
    basis : Vec<String>,
}

/// Runs one method in a child process, or returns `None` after the time limit.
fn run_child(method : &str, threads : usize, generators : &[P], timeout : Duration) -> Option<Run> {
    let mut child = Command::new(std::env::current_exe().unwrap())
        .args(["--child", method, &threads.to_string()])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .expect("cannot start the child process");
    let input : String = generators.iter().map(|g| to_syntax(g) + "\n").collect();
    child.stdin.take().unwrap().write_all(input.as_bytes()).unwrap();
    let mut stdout = child.stdout.take().unwrap();
    let reader = std::thread::spawn(move || {
        let mut output = String::new();
        stdout.read_to_string(&mut output).unwrap();
        output
    });
    let start = Instant::now();
    while child.try_wait().unwrap().is_none() {
        if start.elapsed() > timeout {
            child.kill().ok();
            child.wait().ok();
            reader.join().ok();
            return None;
        }
        std::thread::sleep(Duration::from_millis(5));
    }
    let output = reader.join().unwrap();
    let mut run = Run { ms : f64::NAN, stats : Stats::default(), basis : Vec::new() };
    for line in output.lines() {
        if let Some(t) = line.strip_prefix("time ") {
            run.ms = t.parse().unwrap();
        } else if let Some(s) = line.strip_prefix("stats ") {
            let v : Vec<usize> = s.split_whitespace().map(|n| n.parse().unwrap()).collect();
            run.stats = Stats { rounds : v[0], reductions : v[1], zero : v[2], discarded : v[3] };
        } else if let Some(p) = line.strip_prefix("poly ") {
            run.basis.push(p.to_string());
        }
    }
    assert!(!run.ms.is_nan(), "the child process failed");
    Some(run)
}

fn main() {
    let args : Vec<String> = std::env::args().skip(1).collect();
    if args.first().map(String::as_str) == Some("--child") {
        child(&args[1], args[2].parse().unwrap());
        return;
    }
    let mut threads : Vec<usize> = vec![1, 2, 4];
    let mut timeout = Duration::from_secs(120);
    let mut csv : Option<File> = None;
    let mut names : Vec<String> = Vec::new();
    let (mut random, mut vars, mut gens, mut terms, mut degree, mut seed) = (0usize, 4u32, 4usize, 4usize, 2u64, 1u64);
    let mut it = args.into_iter();
    while let Some(arg) = it.next() {
        let mut value = || it.next().unwrap_or_else(|| panic!("{arg} needs a value"));
        match arg.as_str() {
            "--threads" => threads = value().split(',').map(|t| t.trim().parse().expect("bad number of threads")).collect(),
            "--timeout" => timeout = Duration::from_secs_f64(value().parse().expect("bad timeout")),
            "--csv" => {
                let mut file = File::create(value()).expect("cannot create the CSV file");
                writeln!(file, "ideal,method,threads,status,ms,speedup,rounds,reductions,zero,discarded,equal").unwrap();
                csv = Some(file);
            }
            "--random" => random = value().parse().expect("bad count"),
            "--vars" => vars = value().parse().expect("bad number of variables"),
            "--gens" => gens = value().parse().expect("bad number of generators"),
            "--terms" => terms = value().parse().expect("bad number of terms"),
            "--degree" => degree = value().parse().expect("bad degree"),
            "--seed" => seed = value().parse().expect("bad seed"),
            name => names.push(name.to_string()),
        }
    }
    let builtin : Vec<(String, Vec<P>)> = vec![
        ("cyclic-4".to_string(), cyclic(4)),
        ("cyclic-5".to_string(), cyclic(5)),
        ("katsura-3".to_string(), katsura(3)),
        ("katsura-4".to_string(), katsura(4)),
        ("katsura-5".to_string(), katsura(5)),
        ("quadrics-4".to_string(), random_ideal(&mut Rng(0x2545f4914f6cdd1d), 4, 4, 4, 2)),
    ];
    let mut ideals : Vec<(String, Vec<P>)> = builtin
        .into_iter()
        .filter(|(name, _)| (names.is_empty() && random == 0) || names.iter().any(|n| name.contains(n.as_str())))
        .collect();
    let mut rng = Rng(0x9e3779b97f4a7c15 ^ seed.wrapping_mul(0x2545f4914f6cdd1d));
    for k in 1..=random {
        ideals.push((format!("random-{vars}-{k}"), random_ideal(&mut rng, vars, gens, terms, degree)));
    }

    println!("time limit {:.0} s per run; {} cores available", timeout.as_secs_f64(), std::thread::available_parallelism().map(|n| n.get()).unwrap_or(1));
    // For each (method, threads): the speedups over the sequential algorithm.
    let mut speedups : Vec<((&str, usize), Vec<f64>)> = Vec::new();
    for (name, generators) in &ideals {
        println!("\n== {name}: {} generators", generators.len());
        println!("  {:<12} {:>7} {:>12} {:>8} {:>7} {:>10} {:>7} {:>9} {:>6}", "method", "threads", "ms", "speedup", "rounds", "reductions", "zero", "discarded", "equal");
        let Some(sequential) = run_child("sequential", 1, generators, timeout) else {
            println!("  sequential: timeout; skipped");
            continue;
        };
        println!("  {:<12} {:>7} {:>12.1} {:>8} {:>7} {:>10} {:>7} {:>9} {:>6}", "sequential", 1, sequential.ms, "1.00", "", "", "", "", "");
        for method in ["batch", "first"] {
            for &t in &threads {
                match run_child(method, t, generators, timeout) {
                    Some(run) => {
                        let speedup = sequential.ms / run.ms;
                        let equal = run.basis == sequential.basis;
                        let s = &run.stats;
                        println!(
                            "  {:<12} {:>7} {:>12.1} {:>8.2} {:>7} {:>10} {:>7} {:>9} {:>6}",
                            method, t, run.ms, speedup, s.rounds, s.reductions, s.zero, s.discarded, if equal { "yes" } else { "NO" }
                        );
                        if let Some(file) = csv.as_mut() {
                            writeln!(file, "{name},{method},{t},done,{:.3},{speedup:.4},{},{},{},{},{equal}", run.ms, s.rounds, s.reductions, s.zero, s.discarded).unwrap();
                        }
                        match speedups.iter_mut().find(|(k, _)| *k == (method, t)) {
                            Some((_, v)) => v.push(speedup),
                            None => speedups.push(((method, t), vec![speedup])),
                        }
                    }
                    None => {
                        println!("  {:<12} {:>7} {:>12}", method, t, "timeout");
                        if let Some(file) = csv.as_mut() {
                            writeln!(file, "{name},{method},{t},timeout,,,,,,,").unwrap();
                        }
                    }
                }
            }
        }
    }
    println!("\n== geometric mean of the speedups over the sequential algorithm");
    for ((method, t), v) in &speedups {
        let mean = (v.iter().map(|s| s.ln()).sum::<f64>() / v.len() as f64).exp();
        println!("  {:<6} {} threads: {:.2} (over {} ideals)", method, t, mean, v.len());
    }
}
