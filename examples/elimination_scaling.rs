//! Compares, for growing numbers of variables, the elimination method with the
//! one-colour trick (and optionally the other methods of
//! `elimination_comparison`) on random ideals of K[x1, ..., xn].
//!
//! Both methods compute a basis B of an ideal I such that, for every set V of
//! variables, the elements of B in K[X_V] form a Gröbner basis of I ∩ K[X_V]:
//!
//! - elimination: the union of the reduced Gröbner bases of the 2^n elimination
//!   ideals, each computed by `ideal::elimination_ideal` (Buchberger's algorithm
//!   for a lexicographic elimination order);
//! - one-colour: `equivariant::one_colour_groebner_basis` with the variables of
//!   `trivial.rs` (proved correct in `README.tex`);
//! - direct: `one_colour::one_colour_basis` with its default options, the same
//!   algorithm without the orbit framework, with the adapted Buchberger
//!   criteria and the pairs in the order of creation;
//! - direct-plain: the same without the criteria, which makes the same
//!   reductions as one-colour;
//! - colouring: `equivariant::equivariant_groebner_basis` (the full trick);
//! - ordinary: `ideal::buchberger`, which does not have the property in general;
//! - gfan: the union of all reduced Gröbner bases, computed by the program
//!   `gfan_bases` of gfan (which must be installed, for example with
//!   `apt-get install gfan`). This is a universal Gröbner basis: it is a
//!   Gröbner basis for every monomial order, so it has the property. gfan runs
//!   directly (not in a child process), its time includes starting it, and it
//!   reports no steps; the last column gives the number of reduced Gröbner
//!   bases (the number of maximal cones of the Gröbner fan).
//!
//! Each method runs on each ideal in a child process that is stopped after
//! `--timeout` seconds, so a hard ideal does not block the experiment. The time
//! is measured in the child and does not include starting the process. When
//! the elimination method finishes, its basis serves as the reference: since it
//! contains a Gröbner basis of every I ∩ K[X_V], another basis B contained in I
//! has the property if and only if, for every V, every leading monomial of an
//! element of the reference in K[X_V] is divisible by the leading monomial of an
//! element of B in K[X_V]. The program checks this for every other method.
//!
//! Usage:
//!
//! ```sh
//! cargo run --release --features equivariant --example elimination_scaling -- \
//!     [--vars 4,5,6] [--count K] [--gens G] [--terms T] [--degree D] [--seed S] \
//!     [--timeout SECONDS] [--methods elimination,one-colour] [--csv FILE]
//! ```
//!
//! - `--vars`: the numbers of variables (default 4,5,6).
//! - `--count`: the number of random ideals for each number of variables
//!   (default 10).
//! - `--gens`, `--terms`, `--degree`: each ideal is generated by G polynomials
//!   (default 3) with T terms (default 3) of degree 1 to D (default 2), with
//!   coefficients in {-2, -1, 1, 2}; with `--gens-per-var R`, the number of
//!   generators is round(R n) instead, so that it grows with n. The polynomials
//!   are drawn again until every variable occurs.
//! - `--seed`: changes the random ideals (default 1).
//! - `--timeout`: the time limit for one method on one ideal (default 30).
//! - `--methods`: a comma-separated list among elimination, one-colour,
//!   direct, direct-plain, colouring, ordinary and gfan (default
//!   elimination,one-colour,direct).
//! - `--csv FILE`: also write one line per ideal and method to FILE.
//! - `--fan` (with the method gfan): for each ideal, compute a weight vector in
//!   the interior of every cone of the Gröbner fan (`gfan_groebnercone
//!   --restrict`), and count, for each method, the cones for whose order its
//!   basis is a Gröbner basis. The order of a cone compares weights first and
//!   breaks ties with the order of `mon.rs`; since the weight vector is in the
//!   interior of the cone, the marked leading terms of the reduced basis of
//!   the cone are its leading terms for this order. A basis contained in the
//!   ideal is a Gröbner basis for this order if and only if each of these
//!   leading monomials is divisible by the leading monomial of one of its
//!   elements. The basis of gfan is a Gröbner basis for every cone.
//!
//! For each ideal and method, the program prints:
//!
//! - ms: the time;
//! - the steps, counted by `counters.rs` (for elimination, summed over the 2^n
//!   elimination ideals): S-polys, the S-polynomials computed; reductions, the
//!   elementary reduction steps (one term cancelled by a multiple of a
//!   reducer, including the final interreduction); added, the polynomials added
//!   to a basis by the main loop of Buchberger's algorithm;
//! - the final basis: size, its number of polynomials; minimal, the number left
//!   after removing every h for which another kept h' has supp(h') ⊆ supp(h)
//!   and LM(h') dividing LM(h) (`minimal_basis`); terms, its total number of
//!   terms;
//! - property: whether the basis has the property (checked against the
//!   elimination bases).
//!
//! For each number of variables, it prints how many ideals each method
//! finished, the medians of these numbers over the ideals that all methods
//! finished, the ratios of the medians of each method to those of the
//! elimination method, and the number of ideals for which the property fails.

use atomic_hilbert::atoms::Orbit;
use atomic_hilbert::counters::{self, Counts};
use atomic_hilbert::equivariant::{equivariant_groebner_basis, minimal_basis, one_colour_groebner_basis, OrbitList};
use atomic_hilbert::ideal::{buchberger, elimination_ideal};
use atomic_hilbert::mon::{Monomial, Polynomial};
use atomic_hilbert::one_colour::{one_colour_basis, Options as DirectOptions};
use atomic_hilbert::trivial::FinOrd;
use num_rational::BigRational;
use num_traits::{One, Pow, Zero};
use std::collections::BTreeSet;
use std::fs::File;
use std::io::{Read, Write};
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

type Q = BigRational;
type P = Polynomial<Q, FinOrd>;

const METHODS : [&str; 7] = ["elimination", "one-colour", "direct", "direct-plain", "colouring", "ordinary", "gfan"];

/// The command-line options of the parent process.
struct Options {
    vars : Vec<u32>,
    count : usize,
    gens : usize,
    gens_per_var : Option<f64>,
    terms : usize,
    degree : u64,
    seed : u64,
    timeout : Duration,
    methods : Vec<String>,
    csv : Option<File>,
    fan : bool,
}

impl Options {
    fn parse(args : Vec<String>) -> Options {
        let mut options = Options {
            vars : vec![4, 5, 6],
            count : 10,
            gens : 3,
            gens_per_var : None,
            terms : 3,
            degree : 2,
            seed : 1,
            timeout : Duration::from_secs(30),
            methods : vec!["elimination".to_string(), "one-colour".to_string(), "direct".to_string()],
            csv : None,
            fan : false,
        };
        let mut args = args.into_iter();
        let number = |v : Option<String>, name : &str| -> u64 { v.and_then(|v| v.parse().ok()).unwrap_or_else(|| panic!("{name} needs a number")) };
        while let Some(arg) = args.next() {
            match arg.as_str() {
                "--vars" => options.vars = args.next().expect("--vars needs a list").split(',').map(|v| v.trim().parse().expect("bad number of variables")).collect(),
                "--count" => options.count = number(args.next(), "--count") as usize,
                "--gens" => options.gens = number(args.next(), "--gens") as usize,
                "--gens-per-var" => options.gens_per_var = Some(args.next().and_then(|v| v.parse().ok()).expect("--gens-per-var needs a number")),
                "--terms" => options.terms = number(args.next(), "--terms") as usize,
                "--degree" => options.degree = number(args.next(), "--degree"),
                "--seed" => options.seed = number(args.next(), "--seed"),
                "--timeout" => options.timeout = Duration::from_secs_f64(args.next().and_then(|v| v.parse().ok()).expect("--timeout needs a number of seconds")),
                "--methods" => {
                    options.methods = args.next().expect("--methods needs a list").split(',').map(|m| m.trim().to_string()).collect();
                    for m in &options.methods {
                        assert!(METHODS.contains(&m.as_str()), "unknown method {m}");
                    }
                    if !options.methods.iter().any(|m| m == "elimination") {
                        println!("note: without the elimination method, the property is not checked");
                    }
                }
                "--fan" => options.fan = true,
                "--csv" => {
                    let path = args.next().expect("--csv needs a file name");
                    let mut file = File::create(&path).expect("cannot create the CSV file");
                    writeln!(file, "variables,ideal,method,status,ms,s_polynomials,reductions,added,size,minimal,terms,property,bases,cones_covered,cones").unwrap();
                    options.csv = Some(file);
                }
                other => panic!("unknown option {other}"),
            }
        }
        options
    }
}

fn x(i : u32) -> P {
    Polynomial::var(FinOrd(i))
}

/// Writes a polynomial in the syntax read by `parse`.
fn to_syntax(p : &P) -> String {
    let terms : Vec<String> = p
        .monomials()
        .map(|m| {
            let mut t = p.coeff_of(m).to_string();
            for factor in m.to_string().trim_matches(|ch| ch == '(' || ch == ')').split_whitespace() {
                if factor != "1" {
                    t += "*";
                    t += factor;
                }
            }
            t
        })
        .collect();
    if terms.is_empty() { "0".to_string() } else { terms.join(" + ") }
}

/// Reads a polynomial written by `to_syntax`: terms separated by `+`, factors by
/// `*`, a factor being a rational coefficient or a variable x<i>^<e>.
fn parse(src : &str) -> P {
    let mut f = P::zero();
    for term in src.split('+').map(str::trim).filter(|t| !t.is_empty()) {
        let mut t = P::constant(Q::one());
        for factor in term.split('*').map(str::trim) {
            if let Some(rest) = factor.strip_prefix('x') {
                let mut it = rest.split('^');
                let i : u32 = it.next().unwrap().parse().expect("bad variable index");
                let e : u32 = it.next().map(|e| e.parse().expect("bad exponent")).unwrap_or(1);
                t = t * x(i).pow(e);
            } else {
                t = t * P::constant(factor.parse::<Q>().expect("bad coefficient"));
            }
        }
        f = f + t;
    }
    f
}

/// A small deterministic pseudo-random generator (xorshift).
struct Rng(u64);

impl Rng {
    fn below(&mut self, n : u64) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0 % n
    }
}

/// A random ideal as described by the options, in which every variable x1, ...,
/// xn occurs.
fn random_ideal(rng : &mut Rng, n : u32, options : &Options) -> Vec<P> {
    let gens = number_of_generators(n, options);
    assert!(gens * options.terms * options.degree as usize >= n as usize, "too few variable slots: raise --gens, --terms or --degree");
    for _ in 0..100_000 {
        let generators : Vec<P> = (0..gens)
            .map(|_| {
                (0..options.terms).fold(P::zero(), |f, _| {
                    let k = [-2, -1, 1, 2][rng.below(4) as usize];
                    let mut t = P::constant(Q::from_integer(k.into()));
                    for _ in 0..1 + rng.below(options.degree) {
                        t = t * x(1 + rng.below(n as u64) as u32);
                    }
                    f + t
                })
            })
            .collect();
        let vars : BTreeSet<FinOrd> = generators.iter().flat_map(|g| g.domain()).collect();
        if generators.iter().all(|g| !g.is_zero()) && vars.len() == n as usize {
            return generators;
        }
    }
    panic!("could not draw an ideal in which all {n} variables occur");
}

/// The number of generators of a random ideal in n variables: `--gens`, or
/// round(R n) (at least 1) with `--gens-per-var R`.
fn number_of_generators(n : u32, options : &Options) -> usize {
    match options.gens_per_var {
        Some(r) => ((r * n as f64).round() as usize).max(1),
        None => options.gens,
    }
}

/// All sets of variables among `vars`.
fn subsets(vars : &[FinOrd]) -> Vec<BTreeSet<FinOrd>> {
    (0..1usize << vars.len())
        .map(|mask| vars.iter().enumerate().filter(|(i, _)| mask >> i & 1 == 1).map(|(_, v)| *v).collect())
        .collect()
}

/// Runs one method on the ideal generated by `generators` (child process).
fn compute(method : &str, generators : &[P]) -> Option<Vec<P>> {
    let polynomials = |b : OrbitList<Q, FinOrd>| -> Vec<P> { b.iter().map(|o| o.evaluate(|p| p.clone())).collect() };
    let orbits = || -> OrbitList<Q, FinOrd> { generators.iter().cloned().map(Orbit::new).collect() };
    match method {
        "elimination" => {
            let vars : Vec<FinOrd> = generators.iter().flat_map(|g| g.domain()).collect::<BTreeSet<FinOrd>>().into_iter().collect();
            let mut union : Vec<P> = Vec::new();
            for v in subsets(&vars) {
                for e in elimination_ideal(generators, &v) {
                    if !union.contains(&e) {
                        union.push(e);
                    }
                }
            }
            Some(union)
        }
        "one-colour" => one_colour_groebner_basis(orbits(), 1_000_000).ok().map(polynomials),
        "direct" => Some(one_colour_basis(generators.to_vec(), DirectOptions::default())),
        "direct-plain" => Some(one_colour_basis(generators.to_vec(), DirectOptions { criteria : false, normal_strategy : false })),
        "colouring" => equivariant_groebner_basis(orbits(), 1_000_000).ok().map(polynomials),
        "ordinary" => Some(buchberger(generators.to_vec())),
        _ => panic!("unknown method {method}"),
    }
}

/// The child process: reads the generators from standard input, one per line,
/// runs the method, and prints its time, its step counts and its basis.
fn child(method : &str) {
    let mut input = String::new();
    std::io::stdin().read_to_string(&mut input).unwrap();
    let generators : Vec<P> = input.lines().filter(|l| !l.trim().is_empty()).map(parse).collect();
    counters::reset();
    let start = Instant::now();
    let basis = compute(method, &generators);
    let time = start.elapsed();
    let counts = counters::get();
    match basis {
        Some(basis) => {
            println!("time {}", time.as_secs_f64() * 1000.0);
            println!("counts {} {} {}", counts.s_polynomials, counts.reductions, counts.added);
            for p in basis {
                println!("poly {}", to_syntax(&p));
            }
        }
        None => println!("limit"),
    }
}

/// The outcome of one method on one ideal.
enum Status {
    /// The time, the step counts (not for gfan), the number of reduced Gröbner
    /// bases (for gfan only) and the basis.
    Done { ms : f64, counts : Option<Counts>, bases : Option<usize>, basis : Vec<P>, raw : Option<String> },
    Timeout,
    Limit,
}

/// Writes a polynomial in the input syntax of gfan, such as `x1^2*x3-3/2*x2+1`.
fn to_gfan(p : &P) -> String {
    let mut out = String::new();
    for m in p.monomials().rev() {
        let c = p.coeff_of(m);
        let written = m.to_string();
        let factors : Vec<&str> = written.trim_matches(|ch| ch == '(' || ch == ')').split_whitespace().filter(|f| *f != "1").collect();
        // Rename x<i> to x<i> with three digits, as in the ring given to gfan.
        let factors : Vec<String> = factors
            .iter()
            .map(|f| {
                let (var, exp) = f.split_once('^').unwrap_or((f, "1"));
                let i : u32 = var.trim_start_matches('x').parse().expect("bad variable");
                format!("x{i:03}^{exp}")
            })
            .collect();
        let monomial = factors.join("*");
        let term = if monomial.is_empty() {
            c.to_string()
        } else if c == Q::one() {
            monomial
        } else if c == -Q::one() {
            format!("-{monomial}")
        } else {
            format!("{c}*{monomial}")
        };
        if !out.is_empty() && !term.starts_with('-') {
            out.push('+');
        }
        out += &term;
    }
    if out.is_empty() { "0".to_string() } else { out }
}

/// Reads a polynomial in the output syntax of gfan.
fn parse_gfan(src : &str) -> P {
    let s : String = src.chars().filter(|c| !c.is_whitespace()).collect();
    // Split into signed terms: a sign starts a new term, except at the start.
    let mut terms : Vec<String> = Vec::new();
    let mut current = String::new();
    for ch in s.chars() {
        if (ch == '+' || ch == '-') && !current.is_empty() {
            terms.push(std::mem::take(&mut current));
        }
        if ch != '+' {
            current.push(ch);
        }
    }
    if !current.is_empty() {
        terms.push(current);
    }
    let mut f = P::zero();
    for term in terms {
        let (sign, body) = match term.strip_prefix('-') {
            Some(rest) => (-Q::one(), rest.to_string()),
            None => (Q::one(), term),
        };
        let mut t = P::constant(sign);
        for factor in body.split('*') {
            if let Some(rest) = factor.strip_prefix('x') {
                let mut it = rest.split('^');
                let i : u32 = it.next().unwrap().parse().expect("bad variable in the output of gfan");
                let e : u32 = it.next().map(|e| e.parse().expect("bad exponent in the output of gfan")).unwrap_or(1);
                t = t * x(i).pow(e);
            } else {
                t = t * P::constant(factor.parse::<Q>().expect("bad coefficient in the output of gfan"));
            }
        }
        f = f + t;
    }
    f
}

/// Runs `gfan_bases`, which computes all reduced Gröbner bases of the ideal,
/// with a time limit, and returns their union (made monic for the order of
/// `mon.rs`, without repetitions), which is a universal Gröbner basis. The time
/// includes starting gfan.
fn run_gfan(generators : &[P], timeout : Duration) -> Status {
    let n = generators.iter().flat_map(|g| g.domain()).map(|v| v.0).max().unwrap_or(1);
    // gfan misreads a variable whose name is a prefix of another one (x1 and
    // x10), so all names have the same length: x001, x002, ...
    let ring : Vec<String> = (1..=n).map(|i| format!("x{i:03}")).collect();
    let input = format!("Q[{}]{{{}}}\n", ring.join(","), generators.iter().map(to_gfan).collect::<Vec<_>>().join(", "));
    let start = Instant::now();
    let mut child = Command::new("gfan_bases")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn()
        .expect("cannot start gfan_bases: is gfan installed?");
    child.stdin.take().unwrap().write_all(input.as_bytes()).unwrap();
    let mut stdout = child.stdout.take().unwrap();
    let reader = std::thread::spawn(move || {
        let mut output = String::new();
        stdout.read_to_string(&mut output).unwrap();
        output
    });
    loop {
        if child.try_wait().unwrap().is_some() {
            break;
        }
        if start.elapsed() > timeout {
            child.kill().ok();
            child.wait().ok();
            reader.join().ok();
            return Status::Timeout;
        }
        std::thread::sleep(Duration::from_millis(1));
    }
    let ms = start.elapsed().as_secs_f64() * 1000.0;
    let output = reader.join().unwrap();
    // The output is the ring on the first line, then {{...},{...},...}.
    let body : String = output.lines().skip(1).collect::<Vec<_>>().join("");
    let bases = body.matches('{').count().saturating_sub(1);
    let union : BTreeSet<P> = body
        .replace(['{', '}'], "")
        .split(',')
        .map(str::trim)
        .filter(|t| !t.is_empty())
        .map(|t| parse_gfan(t).monic())
        .collect();
    Status::Done { ms, counts : None, bases : Some(bases), basis : union.into_iter().collect(), raw : Some(output) }
}

/// Runs one method on one ideal in a child process, with a time limit.
fn run_child(method : &str, generators : &[P], timeout : Duration) -> Status {
    let exe = std::env::current_exe().unwrap();
    let mut child = Command::new(exe)
        .args(["--child", method])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .expect("cannot start the child process");
    let input : String = generators.iter().map(|g| to_syntax(g) + "\n").collect();
    child.stdin.take().unwrap().write_all(input.as_bytes()).unwrap();
    let mut stdout = child.stdout.take().unwrap();
    let reader = std::thread::spawn(move || {
        let mut output = String::new();
        stdout.read_to_string(&mut output).unwrap();
        output
    });
    let start = Instant::now();
    loop {
        if child.try_wait().unwrap().is_some() {
            break;
        }
        if start.elapsed() > timeout {
            child.kill().ok();
            child.wait().ok();
            reader.join().ok();
            return Status::Timeout;
        }
        std::thread::sleep(Duration::from_millis(5));
    }
    let output = reader.join().unwrap();
    let mut ms = None;
    let mut counts = Counts::default();
    let mut basis = Vec::new();
    for line in output.lines() {
        if line == "limit" {
            return Status::Limit;
        } else if let Some(t) = line.strip_prefix("time ") {
            ms = Some(t.parse().unwrap());
        } else if let Some(c) = line.strip_prefix("counts ") {
            let v : Vec<u64> = c.split_whitespace().map(|n| n.parse().unwrap()).collect();
            counts = Counts { s_polynomials : v[0], reductions : v[1], added : v[2] };
        } else if let Some(p) = line.strip_prefix("poly ") {
            basis.push(parse(p));
        }
    }
    Status::Done { ms : ms.expect("the child process failed"), counts : Some(counts), bases : None, basis, raw : None }
}

/// A cone of the Gröbner fan: a weight vector in its interior, and the leading
/// monomials of its reduced Gröbner basis.
struct Cone {
    weight : Vec<i128>,
    leading : Vec<Monomial<FinOrd>>,
}

/// The reduced Gröbner bases in the output of `gfan_bases`, as lists of
/// polynomials in the syntax of gfan; the first term of each polynomial is its
/// leading term.
fn parse_fan(raw : &str) -> Vec<Vec<String>> {
    let body : String = raw.lines().skip(1).collect::<Vec<_>>().join("");
    let mut bases = Vec::new();
    let mut depth = 0;
    let mut current = String::new();
    for ch in body.chars() {
        match ch {
            '{' => {
                depth += 1;
                if depth == 2 {
                    current.clear();
                }
            }
            '}' => {
                if depth == 2 {
                    bases.push(current.split(',').map(|t| t.trim().to_string()).filter(|t| !t.is_empty()).collect());
                }
                depth -= 1;
            }
            _ if depth == 2 => current.push(ch),
            _ => {}
        }
    }
    bases
}

/// The first term of a polynomial in the syntax of gfan.
fn first_term(p : &str) -> &str {
    let end = p.char_indices().skip(1).find(|(_, c)| *c == '+' || *c == '-').map(|(i, _)| i).unwrap_or(p.len());
    &p[..end]
}

/// The cones of the Gröbner fan in the output of `gfan_bases`. A weight vector
/// in the interior of each cone, restricted to the non-negative orthant, is
/// computed by `gfan_groebnercone --restrict`.
fn cones(raw : &str) -> Vec<Cone> {
    let ring = raw.lines().next().unwrap_or("");
    parse_fan(raw)
        .into_iter()
        .map(|basis| {
            let input = format!("{ring}\n{{{}}}\n", basis.join(","));
            let mut child = Command::new("gfan_groebnercone")
                .arg("--restrict")
                .stdin(Stdio::piped())
                .stdout(Stdio::piped())
                .stderr(Stdio::null())
                .spawn()
                .expect("cannot start gfan_groebnercone");
            child.stdin.take().unwrap().write_all(input.as_bytes()).unwrap();
            let mut output = String::new();
            child.stdout.take().unwrap().read_to_string(&mut output).unwrap();
            child.wait().unwrap();
            let mut lines = output.lines().skip_while(|l| l.trim() != "RELATIVE_INTERIOR_POINT");
            lines.next();
            let weight : Vec<i128> = lines
                .next()
                .expect("no interior point in the output of gfan_groebnercone")
                .split_whitespace()
                .map(|w| w.parse().expect("the interior point is not an integer vector"))
                .collect();
            let leading = basis.iter().map(|g| parse_gfan(first_term(g)).leading_mon()).collect();
            Cone { weight, leading }
        })
        .collect()
}

/// The weight of a monomial for the weight vector `w` (variable i has weight w[i - 1]).
fn weight(m : &Monomial<FinOrd>, w : &[i128]) -> i128 {
    m.exponents().map(|(v, e)| w[(v.0 - 1) as usize] * e as i128).sum()
}

/// The leading monomial of p for the order that compares the weights for `w`
/// first, and breaks ties with the order of `mon.rs`.
fn weighted_leading(p : &P, w : &[i128]) -> Monomial<FinOrd> {
    p.monomials().max_by(|a, b| (weight(a, w), *a).cmp(&(weight(b, w), *b))).unwrap().clone()
}

/// The number of cones for whose order `basis` (contained in the ideal) is a
/// Gröbner basis: every leading monomial of the reduced basis of the cone must
/// be divisible by the leading monomial of an element of `basis`.
fn cones_covered(basis : &[P], cones : &[Cone]) -> usize {
    cones
        .iter()
        .filter(|cone| {
            let leading : Vec<Monomial<FinOrd>> = basis.iter().filter(|b| !b.is_zero()).map(|b| weighted_leading(b, &cone.weight)).collect();
            cone.leading.iter().all(|l| leading.iter().any(|m| l.is_divisible_by(m)))
        })
        .count()
}

/// Whether `basis` has the property for every set V, with `reference` as above.
fn has_property(basis : &[P], reference : &[P], vars : &[FinOrd]) -> bool {
    subsets(vars).iter().all(|v| {
        let inside : Vec<&P> = basis.iter().filter(|h| !h.is_zero() && h.domain().is_subset(v)).collect();
        reference
            .iter()
            .filter(|e| e.domain().is_subset(v))
            .all(|e| inside.iter().any(|h| e.leading_mon().is_divisible_by(&h.leading_mon())))
    })
}

fn minimal_size(basis : &[P]) -> usize {
    minimal_basis(basis.iter().cloned().map(Orbit::new).collect()).len()
}

/// The median of the values that are not NaN (NaN if there is none).
fn median(values : &mut [f64]) -> f64 {
    let mut v : Vec<f64> = values.iter().copied().filter(|x| !x.is_nan()).collect();
    v.sort_by(|a, b| a.partial_cmp(b).unwrap());
    if v.is_empty() { f64::NAN } else { v[v.len() / 2] }
}

/// A number for a table cell, or "-" if it is NaN.
fn cell(v : f64, width : usize, digits : usize) -> String {
    if v.is_nan() { format!("{:>width$}", "-") } else { format!("{v:>width$.digits$}") }
}

fn main() {
    let args : Vec<String> = std::env::args().skip(1).collect();
    if args.first().map(String::as_str) == Some("--child") {
        child(&args[1]);
        return;
    }
    let mut options = Options::parse(args);
    let mut rng = Rng(0x9e3779b97f4a7c15 ^ options.seed.wrapping_mul(0x2545f4914f6cdd1d));
    let methods = options.methods.clone();
    let generators_text = match options.gens_per_var {
        Some(r) => format!("round({r} n)"),
        None => options.gens.to_string(),
    };
    println!(
        "random ideals: {} generators with {} terms of degree 1 to {}; time limit {:.0} s per method and ideal",
        generators_text,
        options.terms,
        options.degree,
        options.timeout.as_secs_f64()
    );
    for &n in &options.vars.clone() {
        println!("\n== {n} variables ({} sets V)", 1u64 << n);
        println!(
            "  {:>5} {:<12} {:>12} {:>10} {:>12} {:>8} {:>6} {:>8} {:>8} {:>9}",
            "ideal", "method", "ms", "S-polys", "reductions", "added", "size", "minimal", "terms", "property"
        );
        // For each method, the metrics on the ideals finished by all methods:
        // ms, S-polynomials, reductions, added, size, minimal size, terms.
        let mut metrics : Vec<Vec<[f64; 7]>> = vec![Vec::new(); methods.len()];
        let mut finished = vec![0usize; methods.len()];
        let mut failing = vec![0usize; methods.len()];
        // With --fan: for each method, the cones covered, the cones, and the
        // ideals for which the basis is a Gröbner basis for every cone.
        let mut fan_totals = vec![(0usize, 0usize, 0usize, 0usize); methods.len()];
        for k in 1..=options.count {
            let generators = random_ideal(&mut rng, n, &options);
            let vars : Vec<FinOrd> = (1..=n).map(FinOrd).collect();
            let statuses : Vec<Status> = methods
                .iter()
                .map(|m| if m == "gfan" { run_gfan(&generators, options.timeout) } else { run_child(m, &generators, options.timeout) })
                .collect();
            let reference = methods.iter().zip(&statuses).find_map(|(m, s)| match (m.as_str(), s) {
                ("elimination", Status::Done { basis, .. }) => Some(basis.clone()),
                _ => None,
            });
            let fan_cones : Option<Vec<Cone>> = if options.fan {
                statuses.iter().find_map(|s| match s {
                    Status::Done { raw : Some(raw), .. } => Some(cones(raw)),
                    _ => None,
                })
            } else {
                None
            };
            let mut row_metrics = Vec::new();
            for (i, (m, s)) in methods.iter().zip(&statuses).enumerate() {
                match s {
                    Status::Done { ms, counts, bases, basis, .. } => {
                        finished[i] += 1;
                        let minimal = minimal_size(basis);
                        let terms : usize = basis.iter().map(|p| p.monomials().count()).sum();
                        let property = match &reference {
                            Some(r) if m != "elimination" => {
                                let ok = has_property(basis, r, &vars);
                                if !ok {
                                    failing[i] += 1;
                                }
                                if ok { "ok" } else { "FAILS" }
                            }
                            _ => "",
                        };
                        let steps = match counts {
                            Some(c) => [c.s_polynomials as f64, c.reductions as f64, c.added as f64],
                            None => [f64::NAN; 3],
                        };
                        let mut fan = bases.map(|b| format!("{b} bases")).unwrap_or_default();
                        let covered = fan_cones.as_ref().map(|c| (cones_covered(basis, c), c.len()));
                        if let Some((k, total)) = covered {
                            fan = format!("cones {k}/{total} {fan}");
                            let t = &mut fan_totals[i];
                            t.0 += k;
                            t.1 += total;
                            t.2 += usize::from(k == total);
                            t.3 += 1;
                        }
                        println!(
                            "  {:>5} {:<12} {:>12.1} {} {} {} {:>6} {:>8} {:>8} {:>9} {}",
                            k, m, ms, cell(steps[0], 10, 0), cell(steps[1], 12, 0), cell(steps[2], 8, 0), basis.len(), minimal, terms, property, fan
                        );
                        if let Some(file) = options.csv.as_mut() {
                            let csv_step = |v : f64| if v.is_nan() { String::new() } else { format!("{v}") };
                            writeln!(
                                file,
                                "{n},{k},{m},done,{ms:.3},{},{},{},{},{minimal},{terms},{},{},{},{}",
                                csv_step(steps[0]), csv_step(steps[1]), csv_step(steps[2]), basis.len(),
                                if property.is_empty() { "unchecked" } else { property },
                                bases.map(|b| b.to_string()).unwrap_or_default(),
                                covered.map(|c| c.0.to_string()).unwrap_or_default(),
                                covered.map(|c| c.1.to_string()).unwrap_or_default()
                            )
                            .unwrap();
                        }
                        row_metrics.push(Some([*ms, steps[0], steps[1], steps[2], basis.len() as f64, minimal as f64, terms as f64]));
                    }
                    Status::Timeout | Status::Limit => {
                        let status = if matches!(s, Status::Timeout) { "timeout" } else { "limit" };
                        println!("  {:>5} {:<12} {:>12}", k, m, status);
                        if let Some(file) = options.csv.as_mut() {
                            writeln!(file, "{n},{k},{m},{status},,,,,,,,,,,").unwrap();
                        }
                        row_metrics.push(None);
                    }
                }
            }
            if row_metrics.iter().all(Option::is_some) {
                for (i, r) in row_metrics.into_iter().enumerate() {
                    metrics[i].push(r.unwrap());
                }
            }
        }
        let names = ["ms", "S-polys", "reductions", "added", "size", "minimal", "terms"];
        println!("  medians over the {} ideals finished by all methods:", metrics[0].len());
        println!("    {:<12} {:>8} {}", "method", "finished", names.iter().map(|n| format!("{n:>12}")).collect::<Vec<_>>().join(""));
        let medians : Vec<Vec<f64>> = metrics
            .iter()
            .map(|rows| (0..7).map(|c| median(&mut rows.iter().map(|r| r[c]).collect::<Vec<f64>>())).collect())
            .collect();
        for (i, m) in methods.iter().enumerate() {
            println!(
                "    {:<12} {:>5}/{:<2} {}   property fails on {}",
                m,
                finished[i],
                options.count,
                medians[i].iter().map(|v| cell(*v, 12, 1)).collect::<Vec<_>>().join(""),
                failing[i]
            );
        }
        if options.fan {
            println!("  cones of the Gröbner fan covered (over all ideals where gfan finished):");
            for (i, m) in methods.iter().enumerate() {
                let (k, total, universal, ideals) = fan_totals[i];
                if ideals > 0 {
                    println!(
                        "    {:<12} {:>6}/{:<6} cones ({:>5.1}%), Gröbner basis for every cone on {}/{} ideals",
                        m, k, total, 100.0 * k as f64 / total as f64, universal, ideals
                    );
                }
            }
        }
        if let Some(e) = methods.iter().position(|m| m == "elimination") {
            for (o, m) in methods.iter().enumerate().filter(|(_, m)| *m != "elimination") {
                println!(
                    "    {:<21} {}",
                    format!("{m}/elim."),
                    (0..7).map(|c| cell(medians[o][c] / medians[e][c], 12, 2)).collect::<Vec<_>>().join("")
                );
            }
        }
    }
}
