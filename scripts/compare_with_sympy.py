"""Compare `buchberger` (through the example `groebner_stdin`) with SymPy.

For random inputs F (polynomials in a, b, c), the script checks that the output H
  (1) lies in the ideal generated by F, and
  (2) has leading monomials that generate the same monomial ideal as SymPy's
      reduced Groebner basis.
(1) and (2) together mean that H is a Groebner basis of the ideal generated by F.
With --reduced, it also checks that H is the reduced Groebner basis.

The monomial order is lexicographic with c > b > a: a larger variable name is
more significant, as in mon.rs.

Usage (from the repository root, with SymPy installed):
    cargo build --release --example groebner_stdin
    python3 scripts/compare_with_sympy.py --field q --trials 100
"""
import argparse
import random
import subprocess
import time

from sympy import Poly, Rational, groebner, symbols

GENS = symbols("c b a")  # c > b > a
NAMES = ["a", "b", "c"]


def random_input(field):
    polys = []
    for _ in range(random.choice([2, 3])):
        terms = {}
        for _ in range(random.randint(1, 4)):
            while True:
                exps = tuple(random.randint(0, 3) for _ in NAMES)
                if sum(exps) <= 3:
                    break
            coeff = 1 if field == "f2" else random.choice([-3, -2, -1, 1, 2, 3])
            terms[exps] = coeff
        polys.append(terms)
    return polys


def to_text(terms):
    parts = []
    for exps, coeff in sorted(terms.items()):
        factors = [str(coeff)]
        factors += [n if e == 1 else f"{n}^{e}" for n, e in zip(NAMES, exps) if e > 0]
        parts.append("*".join(factors))
    return " + ".join(parts)


def to_expr(terms):
    a, b, c = symbols("a b c")
    return sum((coeff * a**ea * b**eb * c**ec for (ea, eb, ec), coeff in terms.items()), 0)


def parse_line(line):
    """Parse the Display format of mon.rs, e.g. '+ -3/2.( a^1 b^2 ) + 1 '."""
    expr = Rational(0)
    for tok in line.strip().split("+"):
        tok = tok.strip()
        if not tok or tok == "0":
            continue
        if ".(" in tok:
            coeff, mono = tok.split(".(", 1)
            term = Rational(coeff)
            for factor in mono.rstrip(")").split():
                name, e = factor.split("^")
                term *= symbols(name) ** int(e)
        else:
            term = Rational(tok)
        expr += term
    return expr


def poly(expr, field):
    if field == "f2":
        return Poly(expr, *GENS, modulus=2)
    return Poly(expr, *GENS, domain="QQ")


def leading_monomial(expr, field):
    return poly(expr, field).monoms(order="lex")[0]


def divides(m1, m2):
    return all(x <= y for x, y in zip(m1, m2))


def canonical(exprs, field):
    return sorted(tuple(poly(e, field).monic().terms(order="lex")) for e in exprs)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--field", choices=["f2", "q"], default="q")
    ap.add_argument("--trials", type=int, default=100)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--timeout", type=float, default=10.0)
    ap.add_argument("--binary", default="target/release/examples/groebner_stdin")
    ap.add_argument("--reduced", action="store_true", help="also require the reduced Groebner basis")
    args = ap.parse_args()

    random.seed(args.seed)
    stats = {"ok": 0, "not_in_ideal": 0, "not_groebner": 0, "not_reduced": 0, "timeout": 0, "crash": 0}
    problems, times = [], []
    for _ in range(args.trials):
        polys = random_input(args.field)
        text = "\n".join(to_text(t) for t in polys)
        options = {"modulus": 2} if args.field == "f2" else {"domain": "QQ"}
        G = groebner([to_expr(t) for t in polys], *GENS, order="lex", **options)
        start = time.time()
        try:
            run = subprocess.run([args.binary, args.field], input=text, capture_output=True,
                                 text=True, timeout=args.timeout)
        except subprocess.TimeoutExpired:
            stats["timeout"] += 1
            problems.append(("timeout", text))
            continue
        times.append(time.time() - start)
        if run.returncode != 0:
            stats["crash"] += 1
            problems.append(("crash", text, run.stderr[-300:]))
            continue
        # Lines starting with '[' are debugging output of older versions of buchberger.
        out = [parse_line(l) for l in run.stdout.splitlines() if l.strip() and not l.startswith("[")]
        out = [e for e in out if e != 0]
        if not all(G.contains(e) for e in out):
            stats["not_in_ideal"] += 1
            problems.append(("not_in_ideal", text))
        elif not all(any(divides(leading_monomial(e, args.field), leading_monomial(g, args.field)) for e in out)
                     for g in G.exprs):
            stats["not_groebner"] += 1
            problems.append(("not_groebner", text))
        elif args.reduced and canonical(out, args.field) != canonical(G.exprs, args.field):
            stats["not_reduced"] += 1
            problems.append(("not_reduced", text))
        else:
            stats["ok"] += 1
    print(f"field {args.field}, {args.trials} trials, seed {args.seed}, time limit {args.timeout} s")
    print("results:", stats)
    if times:
        print(f"slowest finished run: {max(times):.2f} s")
    for p in problems[:5]:
        print("problem:", p)


if __name__ == "__main__":
    main()
